#!/usr/bin/env python3
"""Add what the block declarations need for the native behaviour (idempotent).

- Every light's block item can be worn on the head (`BaseBlockItem implements Equipable`,
  `getEquipmentSlot() == HEAD`): the `minecraft:equippable` component.
- A lamp post's item carries the sword-like attributes `LampPostItem.createAttributes` gives it
  (attack damage +4, attack speed -2 in the main hand).
- A lamp post answers its light by position (only the top block emits), so its blocks declare
  `dynamic_light`.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
for path in sorted((ROOT / "data/simplylight/sunrise/block").glob("*.json")):
    block = json.loads(path.read_text())
    components = block.setdefault("components", {})
    components["minecraft:equippable"] = {"slot": "head"}
    if path.stem.startswith("lamp_post"):
        block["properties"]["dynamic_light"] = True
        components["minecraft:attribute_modifiers"] = [
            {"type": "minecraft:attack_damage", "id": "minecraft:base_attack_damage",
             "amount": 4.0, "operation": "add_value", "slot": "mainhand"},
            {"type": "minecraft:attack_speed", "id": "minecraft:base_attack_speed",
             "amount": -2.0, "operation": "add_value", "slot": "mainhand"},
        ]
    path.write_text(json.dumps(block, indent=2) + "\n")

ids = sorted(
    "simplylight:" + str(p.relative_to(ROOT / "data/simplylight/recipe").with_suffix(""))
    for p in (ROOT / "data/simplylight/recipe").rglob("*.json")
)
(ROOT / "src/recipes.rs").write_text(
    "//! The mod's recipe ids, one per file under `data/simplylight/recipe/` (generated by `tools/gen_behaviour.py`).\n\n"
    "pub const RECIPES: &[&str] = &[\n" + "".join(f'    "{i}",\n' for i in ids) + "];\n"
)
